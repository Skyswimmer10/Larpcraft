const click = async element => { expect(element).toBeTruthy(); await act(async () => { element.click(); }); };
const button = (label, scope = document) => [...scope.querySelectorAll('button')].find(element => element.textContent.trim() === label || element.getAttribute('aria-label') === label);
const field = (label, scope = document) => {
  const element = [...scope.querySelectorAll('label')].find(element => element.textContent.trim() === label || element.querySelector(':scope > span')?.textContent.trim() === label);
  return element?.htmlFor ? document.getElementById(element.htmlFor) : element?.querySelector('input,select,textarea');
};
const input = async (element, value) => {
  expect(element).toBeTruthy();
  await act(async () => {
    element.focus();
    const prototype = element.tagName === 'TEXTAREA' ? HTMLTextAreaElement.prototype : element.tagName === 'SELECT' ? HTMLSelectElement.prototype : HTMLInputElement.prototype;
    Object.getOwnPropertyDescriptor(prototype, 'value').set.call(element, value);
    element.dispatchEvent(new Event(element.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true }));
  });
};

